#!/usr/bin/env python3
"""Builds src/data/birthdates.js from data/births/*.txt (lines 'Name|dd.mm.yyyy', source: DFB-Datencenter etc.).
Keys are the normalized name tokens sorted alphabetically, so 'Min-Jae Kim' and 'Kim Min-jae' match.
Run: python3 tools/build_births.py"""
import json, os, re, unicodedata
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, OUT = os.path.join(ROOT, 'data', 'births'), os.path.join(ROOT, 'src', 'data', 'birthdates.js')
def key(name):
    s = unicodedata.normalize('NFD', name.lower())
    s = ''.join(c for c in s if unicodedata.category(c) != 'Mn').replace('ø', 'o').replace('ß', 'ss').replace('ł', 'l').replace('ı', 'i').replace('æ', 'ae')
    return ' '.join(sorted(t for t in re.split(r'[^a-z0-9]+', s) if t))
out = {}
for f in sorted(os.listdir(SRC)):
    if not f.endswith('.txt'): continue
    for line in open(os.path.join(SRC, f), encoding='utf-8'):
        m = re.match(r'\s*(.+?)\s*\|\s*(\d{2})\.(\d{2})\.(\d{4})\s*$', line)
        if m: out[key(m.group(1))] = f'{m.group(4)}-{m.group(3)}-{m.group(2)}'
with open(OUT, 'w', encoding='utf-8') as fh:
    fh.write('// Generated by tools/build_births.py from data/births – real birth dates, keyed by sorted name tokens.\n')
    fh.write('export const BIRTHDATES = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(out), 'birth dates ->', OUT)
