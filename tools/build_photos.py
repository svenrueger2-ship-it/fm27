#!/usr/bin/env python3
"""Builds src/data/playerPhotos.js from assets/photos/<Vorname Nachname>.png|jpg|webp.
Each photo is cropped square (top-anchored), shrunk to 200 px and stored as a WebP data URL,
keyed by the normalized player name. Run: python3 tools/build_photos.py"""
import base64, io, json, os, re, unicodedata
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC, OUT = os.path.join(ROOT, 'assets', 'photos'), os.path.join(ROOT, 'src', 'data', 'playerPhotos.js')
def norm(s):
    s = unicodedata.normalize('NFD', s.lower())
    return re.sub(r'[^a-z0-9]', '', ''.join(c for c in s if unicodedata.category(c) != 'Mn'))
photos = {}
for f in sorted(os.listdir(SRC)):
    if not re.search(r'\.(png|jpe?g|webp)$', f, re.I): continue
    im = Image.open(os.path.join(SRC, f)).convert('RGB')
    s = min(im.size); x = (im.width - s) // 2; y = int((im.height - s) * 0.12) if im.height > im.width else 0
    im = im.crop((x, y, x + s, y + s)).resize((200, 200), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'WEBP', quality=82)
    photos[norm(os.path.splitext(f)[0])] = 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
with open(OUT, 'w') as fh:
    fh.write('// Generated by tools/build_photos.py from assets/photos – real player photos, keyed by normalized name.\n')
    fh.write('export const PLAYER_PHOTOS = ' + json.dumps(photos, separators=(',', ':')) + ';\n')
print(len(photos), 'photos ->', OUT)
